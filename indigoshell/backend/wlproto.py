"""Wayland protocol bindings, generated at run time.

pywayland ships bindings for core Wayland and some of wayland-protocols,
but not for wlr-layer-shell, and a system package's set drifts with the
system. So the bindings the shell needs are generated by pywayland's own
scanner from the XML files installed on this machine, into the cache
(`<cache>/indigoshell/wayland-protocols/<key>/`), never into the
repository, once per change of the inputs (the key hashes pywayland's
version and each file's path, size and mtime).

    from indigoshell.backend import wlproto
    wl = wlproto.load()
    wl.wayland.WlCompositor, wl.wlr_layer_shell_unstable_v1.ZwlrLayerShellV1

The generated files import each other relatively (`from .wayland import
WlSurface`), so they are written as one package, `wlproto`, and every
interface the shell binds comes from that package — none from
`pywayland.protocol`, whose classes are a different set.

Standard library and pywayland only.
"""

import glob
import hashlib
import importlib
import logging
import os
import sys
import types

log = logging.getLogger(__name__)

SYSTEM = "/usr/share/wayland/wayland.xml"
STABLE = "/usr/share/wayland-protocols/stable"
STAGING = "/usr/share/wayland-protocols/staging"
WLR = "/usr/share/wlr-protocols/unstable"

# Core first: the scanner resolves a name to the first protocol that
# defines it, and everything else refers to wl_surface and friends.
XML = [
    SYSTEM,
    f"{STABLE}/xdg-shell/xdg-shell.xml",
    f"{STABLE}/viewporter/viewporter.xml",
    f"{WLR}/wlr-layer-shell-unstable-v1.xml",
    f"{WLR}/wlr-virtual-pointer-unstable-v1.xml",
    f"{WLR}/wlr-foreign-toplevel-management-unstable-v1.xml",
    f"{STAGING}/single-pixel-buffer/single-pixel-buffer-v1.xml",
    f"{STAGING}/ext-background-effect/ext-background-effect-v1.xml",
    f"{STAGING}/cursor-shape/cursor-shape-v1.xml",
    f"{STAGING}/fractional-scale/fractional-scale-v1.xml",
    # cursor-shape refers to the tablet tool.
    f"{STABLE}/tablet/tablet-v2.xml",
]

# The ones the shell cannot run without; the rest it does without.
REQUIRED = (SYSTEM, f"{WLR}/wlr-layer-shell-unstable-v1.xml")

PACKAGE = "wlproto"

# Not in wayland-protocols or wlr-protocols: the virtual keyboard, which
# only the tests' input driver uses, from whichever installed package
# happens to carry its XML (qtile's Wayland backend does).
OPTIONAL = {
    "virtual-keyboard-unstable-v1.xml": [
        "/usr/share/wayland-protocols/misc/virtual-keyboard-unstable-v1.xml",
        "/usr/lib/python3*/site-packages/libqtile/backend/wayland/proto/"
        "virtual-keyboard-unstable-v1.xml",
    ],
}


class ProtocolsMissing(RuntimeError):
    pass


def _optional() -> list[str]:
    found = []
    for patterns in OPTIONAL.values():
        for pattern in patterns:
            hits = sorted(glob.glob(pattern))
            if hits:
                found.append(hits[-1])
                break
    return found


def cache_root() -> str:
    from ..core.paths import cache_dir
    return os.path.join(cache_dir(), "wayland-protocols")


def key(files: list[str]) -> str:
    """What the generated package depends on: pywayland's scanner and
    each input file."""
    import pywayland
    h = hashlib.sha256(pywayland.__version__.encode())
    for path in files:
        st = os.stat(path)
        h.update(f"{path}:{st.st_size}:{st.st_mtime_ns}".encode())
    return h.hexdigest()[:16]


def _generate(files: list[str], out: str) -> None:
    from pywayland.scanner.protocol import Protocol

    protocols = [Protocol.parse_file(path) for path in files]
    # The scanner's own main: an interface name maps to the protocol
    # that defines it, the current protocol's own names winning.
    names = {i.name: p.name for p in reversed(protocols) for i in p.interface}
    # A directory of this process's own: two shells starting at once
    # each write theirs, and the first to finish wins the rename.
    tmp = f"{out}.tmp{os.getpid()}"
    os.makedirs(tmp, exist_ok=True)
    for p in protocols:
        imports = dict(names)
        imports.update({i.name: p.name for i in p.interface})
        p.output(tmp, imports)
    with open(os.path.join(tmp, "__init__.py"), "w") as f:
        f.write("# generated by indigoshell/backend/wlproto.py\n")
    try:
        os.replace(tmp, out)
    except OSError:
        if not os.path.isdir(out):
            raise
        import shutil
        shutil.rmtree(tmp, ignore_errors=True)


_loaded: types.SimpleNamespace | None = None


def load() -> types.SimpleNamespace:
    """Every generated protocol module, by protocol name."""
    global _loaded
    if _loaded is not None:
        return _loaded
    missing = [p for p in REQUIRED if not os.path.exists(p)]
    if missing:
        raise ProtocolsMissing(f"protocol XML not installed: {', '.join(missing)}")
    files = [p for p in XML if os.path.exists(p)]
    skipped = sorted(set(XML) - set(files))
    if skipped:
        log.debug("protocols not installed, skipped: %s", skipped)
    files += _optional()
    root = os.path.join(cache_root(), key(files))
    pkg = os.path.join(root, PACKAGE)
    if not os.path.isdir(pkg):
        log.info("generating Wayland protocol bindings into %s", root)
        os.makedirs(root, exist_ok=True)
        _generate(files, pkg)
    if root not in sys.path:
        sys.path.insert(0, root)
    ns = types.SimpleNamespace()
    for name in sorted(os.listdir(pkg)):
        if name.endswith(".py") and name != "__init__.py":
            mod = name[:-3]
            setattr(ns, mod, importlib.import_module(f"{PACKAGE}.{mod}"))
    _loaded = ns
    return ns
