"""Wayland protocol bindings, generated at run time.

pywayland ships bindings for core Wayland and wayland-protocols, but not
for wlr-layer-shell, and a system package's set drifts with the system.
So the bindings this prototype needs are generated by pywayland's own
scanner from the XML files installed on this machine, into a cache dir
(never into the repo), once per change of the inputs.

    from protocols import load
    wl = load()
    wl.wayland.WlCompositor, wl.wlr_layer_shell_unstable_v1.ZwlrLayerShellV1

The generated files import each other relatively (`from .wayland import
WlSurface`), so they are written as one package, `wlproto`, and every
interface the prototype binds comes from that package — none from
`pywayland.protocol`, whose classes are a different set.
"""

import hashlib
import importlib
import os
import sys
import types

SYSTEM = "/usr/share/wayland/wayland.xml"
STABLE = "/usr/share/wayland-protocols/stable"
STAGING = "/usr/share/wayland-protocols/staging"
WLR = "/usr/share/wlr-protocols/unstable"

# Core first: the scanner resolves a name to the first protocol that
# defines it, and everything else refers to wl_surface and friends.
XML = [
    SYSTEM,
    f"{STABLE}/xdg-shell/xdg-shell.xml",
    f"{STABLE}/viewporter/viewporter.xml",
    f"{WLR}/wlr-layer-shell-unstable-v1.xml",
    f"{WLR}/wlr-virtual-pointer-unstable-v1.xml",
    f"{WLR}/wlr-foreign-toplevel-management-unstable-v1.xml",
    f"{STAGING}/single-pixel-buffer/single-pixel-buffer-v1.xml",
    f"{STAGING}/ext-background-effect/ext-background-effect-v1.xml",
    f"{STAGING}/cursor-shape/cursor-shape-v1.xml",
    f"{STAGING}/fractional-scale/fractional-scale-v1.xml",
    # cursor-shape refers to the tablet tool.
    f"{STABLE}/tablet/tablet-v2.xml",
]

PACKAGE = "wlproto"

# Not in wayland-protocols or wlr-protocols; poke.py uses it when some
# installed package happens to carry the XML (qtile's Wayland backend does).
OPTIONAL = {
    "virtual-keyboard-unstable-v1.xml": [
        "/usr/share/wayland-protocols/misc/virtual-keyboard-unstable-v1.xml",
        "/usr/lib/python3*/site-packages/libqtile/backend/wayland/proto/"
        "virtual-keyboard-unstable-v1.xml",
    ],
}


def _optional() -> list[str]:
    import glob
    found = []
    for patterns in OPTIONAL.values():
        for pattern in patterns:
            hits = sorted(glob.glob(pattern))
            if hits:
                found.append(hits[-1])
                break
    return found


def _cache_root() -> str:
    base = os.environ.get("XDG_CACHE_HOME") or os.path.expanduser("~/.cache")
    return os.path.join(base, "indigoshell", "wayland-protocols")


def _key(files: list[str]) -> str:
    import pywayland
    h = hashlib.sha256(pywayland.__version__.encode())
    for path in files:
        st = os.stat(path)
        h.update(f"{path}:{st.st_size}:{st.st_mtime_ns}".encode())
    return h.hexdigest()[:16]


def _generate(files: list[str], out: str) -> None:
    from pywayland.scanner.protocol import Protocol

    protocols = [Protocol.parse_file(path) for path in files]
    # The scanner's own main: an interface name maps to the protocol
    # that defines it, the current protocol's own names winning.
    names = {i.name: p.name for p in reversed(protocols) for i in p.interface}
    tmp = out + ".tmp"
    os.makedirs(tmp, exist_ok=True)
    for p in protocols:
        imports = dict(names)
        imports.update({i.name: p.name for i in p.interface})
        p.output(tmp, imports)
    with open(os.path.join(tmp, "__init__.py"), "w") as f:
        f.write("# generated by prototypes/wayland/protocols.py\n")
    os.replace(tmp, out)


def load() -> types.SimpleNamespace:
    files = [p for p in XML if os.path.exists(p)]
    missing = sorted(set(XML) - set(files))
    if missing:
        print(f"protocols: not installed, skipped: {missing}", file=sys.stderr)
    files += _optional()
    root = os.path.join(_cache_root(), _key(files))
    pkg = os.path.join(root, PACKAGE)
    if not os.path.isdir(pkg):
        os.makedirs(root, exist_ok=True)
        _generate(files, pkg)
    if root not in sys.path:
        sys.path.insert(0, root)
    ns = types.SimpleNamespace()
    for name in sorted(os.listdir(pkg)):
        if name.endswith(".py") and name != "__init__.py":
            mod = name[:-3]
            setattr(ns, mod, importlib.import_module(f"{PACKAGE}.{mod}"))
    return ns


if __name__ == "__main__":
    wl = load()
    print(sorted(vars(wl)))
